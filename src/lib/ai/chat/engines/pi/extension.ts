import "server-only";

import { createHash } from "node:crypto";
import { mkdir, rename, stat, writeFile } from "node:fs/promises";
import path from "node:path";

import { PI_GATE_COMMAND } from "./commands";

// Sentinel's Pi extension (design §4, after t3code packages/provider-pi/src/
// server/mcpExtensionSource.ts, MIT). Pi leaves permission policy to
// extensions: this one asks before every tool call through Pi's blocking
// `tool_call` hook, as an extension UI `confirm` whose message carries the
// call (PI_APPROVAL_PREFIX + JSON), and blocks the call when the answer is
// no. Sentinel's runtime answers each confirm through the shared permission
// policy (read-only tools at once, edits by scope under accept_edits,
// everything under full access, nothing when tools are off or nobody can
// answer), so changing the permission mode never restarts Pi. The extension
// imports nothing (Pi loads it with jiti from a file Sentinel writes under
// the instance's state dir, content-hashed) and registers a command the
// runtime looks for to know the gate is active. MCP bridging is not part
// of it (Pi has no MCP client; see the catalog's supportsMcpInjection).

export const PI_APPROVAL_PREFIX = "sentinel-tool-call:";

export const PI_EXTENSION_SOURCE = `// Generated by Sentinel: asks Sentinel before Pi runs a tool. Do not edit.
const PREFIX = ${JSON.stringify(PI_APPROVAL_PREFIX)};

export default function sentinelPermissionGate(pi: any) {
  pi.registerCommand(${JSON.stringify(PI_GATE_COMMAND)}, {
    description: "Sentinel tool approvals (internal)",
    handler: async () => {},
  });

  pi.on("tool_call", async (event: any, ctx: any) => {
    const toolName = String(event?.toolName ?? "tool");
    if (!ctx?.hasUI || !ctx.ui?.confirm) {
      return { block: true, reason: toolName + " needs approval, and Sentinel is not connected." };
    }
    const message = PREFIX + JSON.stringify({
      input: event?.input ?? null,
      toolCallId: event?.toolCallId ?? null,
      toolName,
    });
    const approved = await ctx.ui.confirm("Allow " + toolName + "?", message, {
      signal: ctx.signal,
    });
    if (!approved) {
      return { block: true, reason: toolName + " was declined in Sentinel." };
    }
  });
}
`;

const EXTENSION_HASH = createHash("sha256")
  .update(PI_EXTENSION_SOURCE)
  .digest("hex")
  .slice(0, 8);

export function piExtensionPath(stateDir: string) {
  return path.join(
    stateDir,
    "pi",
    `sentinel-pi-extension.${EXTENSION_HASH}.ts`,
  );
}

export type PiToolApproval = {
  input: unknown;
  toolCallId: string | null;
  toolName: string;
};

/** The tool call a Sentinel gate confirm asks about (null for other confirms). */
export function readPiToolApproval(message: unknown): PiToolApproval | null {
  if (typeof message !== "string" || !message.startsWith(PI_APPROVAL_PREFIX)) {
    return null;
  }
  try {
    const parsed = JSON.parse(message.slice(PI_APPROVAL_PREFIX.length)) as {
      input?: unknown;
      toolCallId?: unknown;
      toolName?: unknown;
    };
    if (typeof parsed.toolName !== "string" || !parsed.toolName) {
      return null;
    }
    return {
      input: parsed.input ?? null,
      toolCallId:
        typeof parsed.toolCallId === "string" && parsed.toolCallId
          ? parsed.toolCallId
          : null,
      toolName: parsed.toolName,
    };
  } catch {
    return null;
  }
}

/** Writes the extension once per content hash; returns its path. */
export async function ensurePiExtension(stateDir: string) {
  const target = piExtensionPath(stateDir);
  const existing = await stat(target).catch(() => null);
  if (existing?.isFile() && existing.size > 0) {
    return target;
  }
  await mkdir(path.dirname(target), { mode: 0o700, recursive: true });
  const temp = `${target}.${process.pid}.${Date.now()}.tmp`;
  await writeFile(temp, PI_EXTENSION_SOURCE, { mode: 0o600 });
  await rename(temp, target);
  return target;
}
